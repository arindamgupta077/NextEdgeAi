export default function AdminSidebar({
  userEmail,
  open,
  onClose,
}: {
  userEmail?: string
  open?: boolean
  onClose?: () => void
}) {
  const pathname = usePathname()
  const router   = useRouter()

  const [badges, setBadges] = useState<Record<string, number>>({})

  const isActive = (href: string) =>
    href === '/admin'
      ? pathname === '/admin'
      : pathname.startsWith(href)

  const handleLogout = async () => {
    const supabase = createClient()
    await supabase.auth.signOut()
    router.push('/admin/login')
    router.refresh()
  }

  // Load notification counts
  useEffect(() => {
    const supabase = createClient()
    Promise.all([
      supabase.from('contact_submissions').select('*', { count: 'exact', head: true }).eq('status', 'new'),
      supabase.from('career_applications').select('*', { count: 'exact', head: true }).eq('status', 'new'),
    ]).then(([{ count: inq }, { count: apps }]) => {
      setBadges({
        '/admin/inquiries':    inq  ?? 0,
        '/admin/applications': apps ?? 0,
      })
    })
  }, [pathname])

  // Close sidebar on route change (mobile)
  useEffect(() => {
    if (open) onClose?.()
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [pathname])

  // Prevent body scroll when mobile sidebar is open
  useEffect(() => {
    if (open) {
      document.body.style.overflow = 'hidden'
    } else {
      document.body.style.overflow = ''
    }
    return () => { document.body.style.overflow = '' }
  }, [open])

  return (
    <>
      {/* Backdrop — mobile only */}
      {open && (
        <div
          className="fixed inset-0 z-40 bg-black/60 backdrop-blur-sm lg:hidden"
          onClick={onClose}
        />
      )}

      <aside className={`
        flex flex-col w-64 bg-[#06060c] border-r border-white/5
        fixed inset-y-0 left-0 z-50 transition-transform duration-300 h-screen overflow-hidden
        lg:static lg:translate-x-0 lg:z-auto lg:h-screen lg:sticky lg:top-0
        ${open ? 'translate-x-0' : '-translate-x-full lg:translate-x-0'}
      `}>
      {/* Logo */}
      <div className="flex items-center gap-2.5 px-6 py-5 border-b border-white/5">
        <Image
          src="/logo.png"
          alt="NextEdgeAI Logo"
          width={110}
          height={34}
          className="h-9 w-auto object-contain"
          priority
        />
        <div>
          <div className="font-bold text-sm leading-tight">
            NextEdge<span className="text-cyan-400">AI</span>
          </div>
          <div className="text-[10px] text-gray-600 uppercase tracking-wider">Admin Portal</div>
        </div>
      </div>

      {/* Nav */}
      <nav className="flex-1 overflow-y-auto px-3 py-4 space-y-1">
        {NAV.map((item) => {
          const active = isActive(item.href)
          return (
            <button
              key={item.href}
              onClick={() => router.push(item.href)}
              className={`w-full flex items-center gap-3 px-3 py-2.5 rounded-xl text-sm font-medium transition-all duration-200 ${
                active
                  ? 'bg-cyan-400/10 text-cyan-400 border border-cyan-400/20'
                  : 'text-gray-500 hover:text-gray-200 hover:bg-white/4'
              }`}
            >
              {item.icon}
              {item.label}
              {badges[item.href] > 0 && (
                <span className="ml-auto inline-flex items-center justify-center min-w-[18px] h-[18px] px-1 rounded-full bg-rose-500/20 border border-rose-500/30 text-[10px] font-semibold text-rose-400">
                  {badges[item.href] > 99 ? '99+' : badges[item.href]}
                </span>
              )}
              {active && badges[item.href] <= 0 && (
                <span className="ml-auto w-1.5 h-1.5 rounded-full bg-cyan-400" />
              )}
            </button>
          )
        })}
      </nav>

      {/* View site link */}
      <div className="px-3 pb-2">
        <a
          href="/"
          target="_blank"
          rel="noopener noreferrer"
          className="flex items-center gap-3 px-3 py-2.5 rounded-xl text-sm text-gray-600 hover:text-gray-400 transition-colors"
        >
          <svg className="w-5 h-5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}>
            <path strokeLinecap="round" strokeLinejoin="round" d="M13.5 6H5.25A2.25 2.25 0 003 8.25v10.5A2.25 2.25 0 005.25 21h10.5A2.25 2.25 0 0018 18.75V10.5m-10.5 6L21 3m0 0h-5.25M21 3v5.25" />
          </svg>
          View Website
        </a>
      </div>

      {/* User + Logout */}
      <div className="px-3 pb-4 border-t border-white/5 pt-3">
        <div className="flex items-center gap-3 px-3 py-2 mb-1">
          <div className="w-8 h-8 rounded-full bg-gradient-to-br from-cyan-500/20 to-indigo-500/20 border border-white/10 flex items-center justify-center text-xs font-bold text-cyan-400 shrink-0">
            {userEmail?.[0]?.toUpperCase() ?? 'A'}
          </div>
          <div className="overflow-hidden">
            <div className="text-xs font-medium text-gray-300 truncate">{userEmail ?? 'Admin'}</div>
            <div className="text-[10px] text-gray-600">Administrator</div>
          </div>
        </div>
        <button
          onClick={handleLogout}
          className="w-full flex items-center gap-3 px-3 py-2 rounded-xl text-sm text-gray-600 hover:text-red-400 hover:bg-red-400/5 transition-all"
        >
          <svg className="w-5 h-5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}>
            <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 9V5.25A2.25 2.25 0 0013.5 3h-6a2.25 2.25 0 00-2.25 2.25v13.5A2.25 2.25 0 007.5 21h6a2.25 2.25 0 002.25-2.25V15M12 9l-3 3m0 0l3 3m-3-3h12.75" />
          </svg>
          Sign Out
        </button>
      </div>
    </aside>
    </>
  )
}
